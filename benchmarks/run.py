"""`python -m benchmarks.run` — the one command that regenerates everything.

    uv run python -m benchmarks.run --out benchmarks/results/$(date +%F)

That is the acceptance criterion in one line: *a full run completes unattended
and is re-runnable by a third party.* Everything it needs is in this repository
— the corpus is generated by `scripts/make_fixtures.py` and committed, the
matrix comes from the registry rather than from a curated list, and the manifest
records the commit, the corpus digest and the version of every backend that took
part.

**Two runs, two units, one table.** This sandbox's egress proxy denies every
tokenizer vocabulary host, so a local run can only count `bytes`. A CI run can
reach `o200k_base`. Both write result files; `python -m benchmarks.merge`
combines them. Because a cell is keyed by tokenizer, **a byte figure can never
land in a token column** — which matters more here than anywhere else in the
project: Phase 7 found the two units disagreeing by 24 points on tabular data
and not even ranking the five serialisation formats in the same order.

**What it deliberately does not do:**

* **It does not parallelise.** Phase 9 gave the batch queue a thread pool; a
  wall-clock measurement taken while three other conversions compete for four
  cores measures the scheduler.
* **It does not choose which backends to include.** The registry is asked which
  ones claim each fixture's format, and every one of them runs.
* **It does not skip a backend that does badly.** That is the whole point.
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import os
import platform
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import replace
from datetime import UTC, datetime
from pathlib import Path

from benchmarks.harness import DEFAULT_TIMEOUT_S, cells_for, run_matrix
from benchmarks.models import CellResult, RunManifest
from benchmarks.report import write_results
from tokenmill import __version__
from tokenmill.core.registry import default_registry
from tokenmill.fidelity import load_ground_truth

__all__ = ["build_manifest", "corpus_items", "main", "observed_versions"]

_log = logging.getLogger(__name__)

#: Where the corpus lives.
DEFAULT_CORPUS = Path(__file__).resolve().parents[1] / "tests" / "fixtures"

#: How many timed repeats per cell by default.
#:
#: Five, not three: with three, the median is the middle value of a sample that
#: one slow run can dominate, and this corpus's fastest cells are ~20 ms where
#: scheduler noise is a real fraction. Five is the smallest N where the median
#: and the spread both say something and a full run still finishes in minutes.
DEFAULT_REPEATS = 5

#: Corpus files to measure. Directories are handled separately because
#: `Source.from_path` treats a repository as a different kind of thing.
_SUFFIXES = frozenset({".pdf", ".docx", ".pptx", ".xlsx", ".html", ".md"})


def corpus_items(corpus: Path) -> list[tuple[str, Path]]:
    """List what to measure, in a stable order.

    Args:
        corpus: The fixture directory.

    Returns:
        ``(name, path)`` for every file, sorted. The repository fixture is
        included: it is a corpus item the plan names, and the repo backends are
        as much a part of this project as the document ones.
    """
    items = sorted(
        (path.name, path)
        for path in corpus.iterdir()
        if path.is_file() and path.suffix.lower() in _SUFFIXES
    )
    repo = corpus / "sample_repo"
    if repo.is_dir():
        items.append(("sample_repo", repo))
    return items


def corpus_digest(corpus: Path) -> str:
    """Digest every corpus file, so a result can be checked against its inputs.

    Args:
        corpus: The fixture directory.

    Returns:
        A short hex digest over each file's name and content, in sorted order.
        Short because it is for spotting a difference, not for security.
    """
    digest = hashlib.sha256()
    for path in sorted(corpus.rglob("*")):
        if not path.is_file() or ".git" in path.parts:
            continue
        digest.update(str(path.relative_to(corpus)).encode("utf-8"))
        digest.update(path.read_bytes())
    return digest.hexdigest()[:16]


def _git(*args: str) -> str | None:
    """Run a git command and return its output, or ``None`` outside a checkout.

    Args:
        *args: The arguments after ``git``.

    Returns:
        The trimmed stdout, or ``None``.
    """
    try:
        completed = subprocess.run(  # noqa: S603 - a fixed argument list, never a string
            ["git", *args],  # noqa: S607 - git from PATH is the intent
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
            cwd=Path(__file__).resolve().parents[1],
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return completed.stdout.strip() if completed.returncode == 0 else None


def build_manifest(
    corpus: Path, tokenizers: Sequence[str], repeats: int, notes: Sequence[str]
) -> RunManifest:
    """Record what this run is a measurement of.

    Args:
        corpus: The fixture directory.
        tokenizers: What is being counted in.
        repeats: Timed runs per cell.
        notes: Anything qualifying the whole run.

    Returns:
        The manifest, with ``backend_versions`` holding one key per installed
        backend and ``None`` for each. The versions themselves are only known
        once a conversion has actually run, so :func:`observed_versions` fills
        them in afterwards; a manifest written straight from this function
        would claim to record provenance it does not have.
    """
    registry = default_registry()
    versions: dict[str, str | None] = {}
    absent: list[str] = []
    for converter in registry:
        availability = converter.is_available()
        if availability:
            versions[converter.info.id] = None
        else:
            absent.append(converter.info.id)

    all_notes = list(notes)
    if absent:
        all_notes.append(
            "backends not installed here, so they have no rows: " + ", ".join(sorted(absent))
        )

    return RunManifest(
        started_at=datetime.now(UTC).isoformat(timespec="seconds"),
        tokenmill_version=__version__,
        git_commit=_git("rev-parse", "HEAD"),
        git_dirty=bool(_git("status", "--porcelain")),
        python=platform.python_version(),
        platform_description=(f"{platform.system()} {platform.release()} on {platform.machine()}"),
        cpu_count=os.cpu_count() or 1,
        corpus_digest=corpus_digest(corpus),
        repeats=repeats,
        tokenizers=list(tokenizers),
        backend_versions=versions,
        notes=all_notes,
    )


def observed_versions(
    results: Sequence[CellResult], known: Mapping[str, str | None]
) -> dict[str, str | None]:
    """Fill in each backend's version from what its cells actually reported.

    A version resolved by asking the registry before the run is a version of
    something that may never have run. This takes the figure the conversion
    itself recorded — a subprocess backend's ``--version`` output, or the
    installed distribution's version — so the manifest describes the run rather
    than the environment.

    Args:
        results: Every cell of the run.
        known: The installed backends, from :func:`build_manifest`. Backends
            with no cells keep their ``None``: installed, never exercised.

    Returns:
        A new mapping. A backend whose cells disagree — impossible in one run,
        but not worth asserting away — reports every value it gave, joined by
        ``", "``, rather than an arbitrary one.

    Raises:
        Nothing.
    """
    seen: dict[str, set[str]] = {}
    for result in results:
        if result.backend_version:
            seen.setdefault(result.backend, set()).add(result.backend_version)
    merged: dict[str, str | None] = dict(known)
    for backend, versions in seen.items():
        merged[backend] = ", ".join(sorted(versions))
    return merged


def main(argv: Sequence[str] | None = None) -> int:
    """Run the matrix and write the results.

    Args:
        argv: Command-line arguments; ``sys.argv[1:]`` when omitted.

    Returns:
        The exit status. **Zero even when cells failed**, because a failed cell
        is a result rather than an error — the run succeeded in measuring that
        the backend fails. A non-zero status is reserved for the run itself not
        completing.
    """
    parser = argparse.ArgumentParser(
        prog="python -m benchmarks.run",
        description="Run the corpus x backends x tokenizers matrix and write the results.",
    )
    parser.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS)
    parser.add_argument("--out", type=Path, required=True, help="Directory to write into.")
    parser.add_argument(
        "--tokenizer",
        action="append",
        dest="tokenizers",
        help=(
            "What to count in; repeatable. Defaults to 'bytes', which needs no "
            "download. Pass o200k_base in an environment that can reach a "
            "vocabulary host."
        ),
    )
    parser.add_argument("--repeats", type=int, default=DEFAULT_REPEATS)
    parser.add_argument(
        "--backend",
        action="append",
        dest="backends",
        help="Only these backends; repeatable. Defaults to every one that claims a fixture.",
    )
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_S)
    parser.add_argument(
        "--allow-network",
        action="store_true",
        help=(
            "Let backends reach the network. Off by default: without it repomix "
            "refuses because npx would download it, which is an honest row. With "
            "it on, repomix takes part and its first timing may include a package "
            "download — the manifest records that the flag was set."
        ),
    )
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.WARNING if args.quiet else logging.INFO,
        format="%(message)s",
        stream=sys.stderr,
    )

    tokenizers = args.tokenizers or ["bytes"]
    truths = dict(load_ground_truth(args.corpus))
    corpus = corpus_items(args.corpus)
    cells = cells_for(corpus, truths, backends=args.backends)

    notes = _environment_notes(tokenizers, allow_network=args.allow_network)
    manifest = build_manifest(args.corpus, tokenizers, args.repeats, notes)

    def progress(index: int, total: int, cell: object, tokenizer: str) -> None:
        if not args.quiet:
            print(f"[{index:>3}/{total}] {cell} ({tokenizer})", file=sys.stderr)

    results: list[CellResult] = list(
        run_matrix(
            cells,
            tokenizers,
            repeats=args.repeats,
            timeout_s=args.timeout,
            allow_network=args.allow_network,
            on_cell=progress,
        )
    )

    manifest = replace(
        manifest, backend_versions=observed_versions(results, manifest.backend_versions)
    )
    paths = write_results(args.out, results, manifest)
    failed = sum(1 for r in results if not r.ok)
    empty = sum(1 for r in results if r.ok and r.empty_output)
    print(
        f"{len(results)} cells ({failed} failed, {empty} empty) -> {paths['markdown']}",
        file=sys.stderr,
    )
    return 0


def _environment_notes(tokenizers: Sequence[str], *, allow_network: bool) -> list[str]:
    """Say what this environment could and could not measure.

    A limitation the reader has to infer is one they will not infer.

    Args:
        tokenizers: What is being counted in.
        allow_network: Whether backends were permitted to reach the network.

    Returns:
        The notes.
    """
    notes: list[str] = []
    if allow_network:
        notes.append(
            "Run with --allow-network, so backends that fetch were able to. "
            "repomix's first conversion may include an npx package download; its "
            "warm-up run absorbs it, but treat its timing as the least reliable "
            "figure here."
        )
    else:
        notes.append(
            "Run without --allow-network. repomix therefore refuses rather than "
            "letting npx download it mid-benchmark, and that refusal is a row."
        )
    if list(tokenizers) == ["bytes"]:
        notes.append(
            "Counted in UTF-8 bytes only. A byte figure is NOT a token figure: on "
            "this project's own tabular data the two disagreed by 24 points and did "
            "not rank the serialisation formats in the same order. Model-token rows "
            "come from a CI run and are merged in."
        )
    from tokenmill.backends.heavy.gpu import detect_gpu

    gpu = detect_gpu()
    if not gpu.usable:
        notes.append(
            f"No usable GPU ({gpu.accelerator.value}), so no heavy backend took part. "
            "Every OCR row is absent rather than zero."
        )
    return notes


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
